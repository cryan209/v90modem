#!/usr/bin/env python3
"""Extract V.FC mapper tables and execute original Courier mapper test vectors.

Requires the sibling courier-emu and a captured 403 ROM; neither is changed.
This enters c749..c788 directly: frame packing, precoding, nonlinear encoding,
training, sample clocks and full-call interoperability are outside its scope.
V.FC is proprietary; firmware addresses replace ITU clause citations here.
"""
import argparse
import hashlib
import json
import os
import random
from pathlib import Path
import struct
import sys


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--emulator', type=Path, required=True)
    parser.add_argument('--rom', type=Path, required=True)
    parser.add_argument('--library', type=Path, required=True,
                        help='prebuilt courier C5x library (no sibling rebuild)')
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--streams', action='store_true',
                        help='also generate two continuous native trellis streams')
    args = parser.parse_args()
    os.environ['COURIER_C5X_LIBRARY'] = str(args.library.resolve(strict=True))
    sys.dont_write_bytecode = True
    sys.path.insert(0, str(args.emulator.resolve()))
    from courier_emu.rom import CourierRom
    from courier_emu.dsp import NativeC5x
    rom = CourierRom.load(args.rom)
    resident, = [o for o in rom.dsp_overlays if o.index == 5]
    overlay, = [o for o in rom.dsp_overlays if o.index == 7]
    words = [0] * 65536
    for o in (resident, overlay):
        payload = rom.data[o.offset:o.offset + o.length]
        words[o.entry_word:o.entry_word + len(payload)//2] = struct.unpack(
            '<%dH' % (len(payload)//2), payload)
    # Refuse another firmware revision whose addresses merely look plausible.
    expected = {
        0xc749: (0x907d, 0x205a, 0xbfb0, 3, 0x905a),
        0xc75e: (0xbf90, 0xaeab, 0xa67f),
        0xcb57: (0x70, 0x101, 2, 4, 10, 0x8a, 0x103),
        0xcb5e: (0x64, 0x101, 2, 0, 0, 0x82, 0x103),
    }
    for address, values in expected.items():
        if tuple(words[address:address + len(values)]) != values:
            raise ValueError('ROM does not match the 403 V.FC mapper profile')
    args.output.mkdir(parents=True, exist_ok=False)
    digest = hashlib.sha256(rom.data).hexdigest()
    header = ['/* Generated by tools/vfc_firmware_vectors.py.',
              ' * Courier 403 ROM SHA-256: ' + digest,
              ' * Resident aeab..afea: 320 packed one-quadrant V.FC points.',
              ' * This is not the differently ordered V.34 superconstellation. */',
              'static const uint16_t vfc_quadrant[320] = {']
    points = words[0xaeab:0xaeab + 320]
    for i in range(0, len(points), 8):
        header.append('    ' + ', '.join('0x%04x' % p for p in points[i:i+8]) + ',')
    header.append('};\n')
    (args.output / 'vfc_mapper_tables.h').write_text('\n'.join(header))
    rows = ['# Firmware c749..c788; unscaled coordinates in integer lattice units.',
            '# code,state,quadrant,index,dibit,next_state,next_quadrant,i,q']
    count = 0
    with NativeC5x(rom) as core:
        core.load_program(rom.data[overlay.offset:overlay.offset + overlay.length],
                          overlay.entry_word)
        # Set page, AR2 and input accumulator, then enter the real mapper.
        driver = (0xbc07, 0xbf0a, 0x023a, 0x8b8a, 0x6950, 0x7980, 0xc749)
        core.load_program(struct.pack('<7H', *driver), 0)
        core.set_mpmc_pin(0)

        def capture(code, state, quadrant, index, dibit, record=True):
            nonlocal count
            # n=6 uncoded low bits, with remaining index bits in the frame's
            # shell output word. We bypass frame construction intentionally.
            for address, value in ((0x3d0, ((index & 63) << 2) | dibit),
                                   (0x3da, quadrant), (0x3b6, state),
                                   (0x3b7, 0xcb57 if code == 32 else 0xcb5e),
                                   (0x3a5, 6), (0x3be, 63), (0x023a, index >> 6)):
                core.set_data(address, value)
            core.set_pc(0)
            for _ in range(150):
                core.step(1)
                if core.state()['pc'] == 0xc789:
                    break
            else:
                raise RuntimeError('firmware mapper did not reach the precoder')
            coordinates = []
            for address in (0x3f8, 0x3f9):
                value = core.data(address)
                value = value - 65536 if value & 0x8000 else value
                if value % 512:
                    raise RuntimeError('mapper point left the expected lattice')
                coordinates.append(value // 512)
            result = (core.data(0x3b6), core.data(0x3da), *coordinates)
            if record:
                rows.append(','.join(map(str, (code, state, quadrant, index, dibit, *result))))
                count += 1
            return result

        for code in (8, 32):
            # Every encoded state, differential state and input dibit.
            for state in range(32):
                for quadrant in range(4):
                    for dibit in range(4):
                        capture(code, state, quadrant, 0, dibit)
            # Every point index, rotation and trellis-subset offset.
            for index in range(160):
                for state in (0, 1):
                    for dibit in range(4):
                        capture(code, state, 0, index, dibit)
        if args.streams:
            rng = random.Random(0x564643)
            stream = ['# code,index,dibit,i,q; continuous native c749..c788, initial states zero']
            for code in (8, 32):
                state = quadrant = 0
                for _ in range(4096):
                    index, dibit = rng.randrange(96), rng.randrange(4)
                    state, quadrant, i, q = capture(code, state, quadrant, index, dibit, False)
                    stream.append(f'{code},{index},{dibit},{i},{q}')
            (args.output / 'trellis-stream.csv').write_text('\n'.join(stream) + '\n')
    (args.output / 'mapper.csv').write_text('\n'.join(rows) + '\n')
    manifest = {'rom_sha256': digest, 'vectors': count,
                'scope': 'isolated original firmware symbol mapper before precoding',
                'emulator_commit': None, 'native_library_sha256': None}
    if args.streams:
        manifest.update(stream_symbols=8192, stream_point_indices=96,
                        stream_initial_state='zero trellis and differential state')
    import subprocess
    manifest['emulator_commit'] = subprocess.check_output(
        ['git', '-C', str(args.emulator), 'rev-parse', 'HEAD'], text=True).strip()
    manifest['emulator_worktree_dirty'] = bool(subprocess.check_output(
        ['git', '-C', str(args.emulator), 'status', '--porcelain'], text=True))
    from courier_emu.dsp import build_library
    manifest['native_library_sha256'] = hashlib.sha256(build_library().read_bytes()).hexdigest()
    (args.output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(json.dumps(manifest))


if __name__ == '__main__':
    main()
