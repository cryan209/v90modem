def symbol_to_point(bit_rate: int, symbol_index: int) -> tuple[float, float]:
    """Map a coded symbol index to its exact I/Q point."""

    try:
        constellation = CONSTELLATIONS[bit_rate]
    except KeyError as exc:
        raise ValueError(f"unsupported V.32bis bit rate: {bit_rate}") from exc

    if not 0 <= symbol_index < len(constellation):
        raise ValueError(
            f"symbol_index must be in range 0..{len(constellation) - 1} for {bit_rate}"
        )
    return constellation[symbol_index]
