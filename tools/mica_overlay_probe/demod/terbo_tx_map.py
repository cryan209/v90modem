"""Generate spandsp-master/src/v32bis_terbo_tx_map.h: the 512-point V.32terbo constellation as a transmitter table.
Index = (word << 3) | (d << 1) | y0, exactly what v17tx.c's diff_and_convolutional_encode() returns with eight bits per
symbol.  Four tables, one per isomorphism of the recovered coder (they differ in unobservable choices: the label->dibit
permutation and the polarity of y0).  Points are in the analysis frame (lattice axes along the axes), warped by kappa
0.40 (V.34 clause 9.7 series) and scaled to the 14400 table's mean power (41.0 per point)."""
import sys, math
from collections import defaultdict
from pointmap_gen import gen, REC, coset
from cmp_map import CONV_ISO
def ung(i,j):
    p=(i+j)&1; ip=i-p; z1=ip&1; i2=ip-z1; j2=j-z1
    return (p,z1,((i2+j2)//2)&1)
C,RM=REC['rec2_z.pkl']; TAB=gen(C,RM)
BYCW={(coset(*p),w):p for p,w in TAB.items()}
CO_OF={ung(*p):coset(*p) for p in TAB}
E=sum((i-C[0])**2+(j-C[1])**2 for i,j in TAB)/512
KAPPA=0.4; CW=KAPPA/E
phi=lambda z:1+z/6+z*z/120
def table(P,flip):
    pts=[]
    for idx in range(512):
        y0=idx&1; d=(idx>>1)&3; word=idx>>3
        z0=y0^flip
        z1=z2=None
        for a in (0,1):
            for b in (0,1):
                if P[z0][2*b+a]==d: z1,z2=a,b
        i,j=BYCW[(CO_OF[(z0,z1,z2)],word)]
        x=complex(i-C[0],j-C[1]); pts.append(x*phi(CW*abs(x)**2))
    return pts
tabs=[table(P,fl) for P,fl in CONV_ISO]
pw=sum(abs(p)**2 for t in tabs[:1] for p in t)/512
scale=math.sqrt(41.0/pw)
out=['/* Generated by tools/mica_overlay_probe/demod/terbo_tx_map.py; do not edit.',
     '   MICA V.32terbo data constellation (512 points, V.34 clause 9.7 warp, kappa 0.40),',
     '   four isomorphism variants of the recovered coder.  See docs/nonstandard_modulation_inventory.md. */',
     'static const float v32bis_terbo_points[4][512][2] =','{']
for t in tabs:
    out.append('    {')
    for k in range(0,512,4):
        out.append('        '+' '.join('{%.5ff,%.5ff},'%(p.real*scale,p.imag*scale) for p in t[k:k+4]))
    out.append('    },')
out.append('};')
open(sys.argv[1] if len(sys.argv)>1 else '/Users/scottcryan/v90modem/spandsp-master/src/v32bis_terbo_tx_map.h','w').write('\n'.join(out)+'\n')
print('scale',scale,'mean power check', sum(abs(p*scale)**2 for p in tabs[0])/512)
