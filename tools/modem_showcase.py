#!/usr/bin/env python3
"""Record real offline engine handshakes as 8 kHz stereo listening WAVs.

Caller is left, answerer right. G.711 expansion happens only on the exported
listening copy; the ordinary closed-loop bearer remains byte-exact. The V.34 profile uses
the existing simulated FDM channel bank.
"""
import argparse
from array import array
import html
import json
from pathlib import Path
import subprocess
import sys
import wave

ROOT = Path(__file__).resolve().parents[1]


def ulaw(code):
    value = (~code) & 255
    sample = (((value & 15) << 3) + 132) << ((value >> 4) & 7)
    return 132 - sample if value & 128 else sample - 132


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'artifacts/modem-showcase')
    args = parser.parse_args()
    out = args.output.resolve()
    out.mkdir(parents=True, exist_ok=True)
    profiles = [
        ('bell103', 'Bell 103 · 300 bit/s FSK', 'B103', ['--both-at', 'AT+MS=B103,0,300,300']),
        ('v21', 'V.21 · 300 bit/s FSK', 'V21', ['--both-at', 'AT+MS=V21,0,300,300']),
        ('bell212a', 'Bell 212A · 1200 bit/s', 'V22BIS', ['--both-at', 'AT+MS=B212,0,1200,1200']),
        ('v22', 'V.22 · 1200 bit/s', 'V22BIS', ['--both-at', 'AT+MS=V22']),
        ('v22bis', 'V.22bis · 2400 bit/s', 'V22BIS', ['--both-env', 'ME_MODE=v22']),
        ('v32', 'V.32 · 9600 bit/s', 'V32BIS', ['--both-at', 'AT+MS=V32']),
        ('v32bis', 'V.32bis · 14400 bit/s', 'V32BIS', ['--both-env', 'ME_MODE=v32bis']),
        ('v34', 'V.34 · full training', 'V34', ['--both-env', 'ME_MODE=v34', '--fdm-slot', '5']),
        ('v90', 'V.90 · PCM downstream', 'V90', ['--call-env', 'ME_V90_ROLE=analogue', '--answer-env', 'ME_V90_JA_HEURISTIC_FALLBACK_MS=0']),
        ('v92', 'V.92 · PCM upstream and downstream', 'V90', ['--both-env', 'ME_MODE=v92', '--both-at', 'AT+PIG=0', '--call-env', 'ME_V90_ROLE=analogue', '--answer-env', 'ME_V90_JA_HEURISTIC_FALLBACK_MS=0', '--both-after', 'ATI6', '--both-expect', 'Modulation         V92']),
        ('v92-short', 'V.92 · short startup', 'V90', ['--both-env', 'ME_MODE=v92', '--both-at', 'AT+PIG=0', '--both-at', 'AT+PQC=0', '--call-env', 'ME_V90_ROLE=analogue', '--answer-env', 'ME_V90_JA_HEURISTIC_FALLBACK_MS=0', '--both-after', 'ATI6', '--both-expect', 'Modulation         V92']),
    ]
    results = []
    for slug, title, expect, extra in profiles:
        folder = out / slug
        for side in ('call', 'answer'):
            (folder / side).mkdir(parents=True, exist_ok=True)
        command = ['./engine_pair_test', '--seconds', '60', '--expect', expect,
                   '--payload-lines', '1', '--hold-seconds', '2',
                   '--both-env', 'ME_DATA_FRAMING=v14']
        for side in ('call', 'answer'):
            command += [f'--{side}-env', f'VPCM_G711_TAP_DIR={folder / side}',
                        f'--{side}-env', f'ME_DUMP_DIR={folder / side}']
        command += extra
        with (folder / 'run.log').open('w') as log:
            try:
                run = subprocess.run(command, cwd=ROOT, stdout=log, stderr=subprocess.STDOUT, timeout=120)
                passed = run.returncode == 0
            except subprocess.TimeoutExpired:
                passed = False
        taps = [(folder / side / 'live-tx.g711').read_bytes() for side in ('call', 'answer')]
        length = min(map(len, taps))
        pcm = array('h')
        for a, b in zip(taps[0][:length], taps[1][:length]):
            pcm.extend((ulaw(a), ulaw(b)))
        if sys.byteorder != 'little':
            pcm.byteswap()
        with wave.open(str(out / f'{slug}.wav'), 'wb') as wav:
            wav.setparams((2, 2, 8000, 0, 'NONE', 'not compressed'))
            wav.writeframes(pcm.tobytes())
        results.append(dict(slug=slug, title=title, passed=passed, seconds=length / 8000, command=command))
        print(f'{slug}: {length / 8000:.2f}s, {"PASS" if passed else "FAIL (see log)"}', flush=True)
    (out / 'manifest.json').write_text(json.dumps(results, indent=2) + '\n')
    cards = ''.join(f'<article><h2>{html.escape(r["title"])}</h2><p>{r["seconds"]:.1f} seconds · {"Connected and payload verified" if r["passed"] else "Incomplete — see run log"}</p><audio controls preload="none" src="{r["slug"]}.wav"></audio><p><a href="{r["slug"]}.wav" download>Download WAV</a> · <a href="{r["slug"]}/run.log">Run log</a></p></article>' for r in results)
    (out / 'index.html').write_text('<!doctype html><meta charset="utf-8"><title>Modem listening room</title><style>body{background:#101923;color:#e5eef7;font:17px system-ui;max-width:850px;margin:50px auto;padding:20px}article{background:#1c2b3b;padding:20px;margin:18px 0;border-radius:12px}a{color:#7fd9db}audio{width:100%}h2{font-size:21px}</style><h1>Modem listening room</h1><p>Real software modem startups, generated by two complete engines over G.711 (V.34 uses the simulated FDM channel bank). Caller in the left channel; answerer in the right. Native 8 kHz audio, with no normalisation or resampling. Offline results do not establish hardware interoperability.</p>' + cards)
    return 0 if all(r['passed'] for r in results) else 1


if __name__ == '__main__':
    raise SystemExit(main())
