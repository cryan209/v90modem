#!/usr/bin/env python3
"""Retain upstream point signs from MicaEmu's independently checked transmitter.

Usage: python3 tools/generate_k56flex_upstream_vectors.py ../MicaEmu
Requires the sibling's training-TX builder and vendored SpanDSP. No files in
this checkout except k56flex_upstream_vectors.h are changed. The source is a
research transmitter, not a hardware recording. Run the sibling's
verify_k56flex_training_tx.py to check it against original 5903/5961/1D5A.
"""
import ctypes as ct
import hashlib
from pathlib import Path
import sys


def main():
    mica = Path(sys.argv[1]).resolve()
    sys.path.insert(0, str(mica / "tools"))
    from build_k56flex_training_tx import build
    lib = ct.CDLL(str(build()))
    lib.mica_k56_training_new.argtypes = [ct.c_uint] * 6
    lib.mica_k56_training_new.restype = ct.c_void_p
    lib.mica_k56_training_report_length.argtypes = [ct.c_void_p, ct.c_uint]
    lib.mica_k56_training_next_point.argtypes = [ct.c_void_p, ct.POINTER(ct.c_float)]
    lib.mica_k56_training_free.argtypes = [ct.c_void_p]
    adapter = mica / "native/k56flex_training_tx.inc"
    digest = hashlib.sha256(adapter.read_bytes()).hexdigest()
    # Discard S/S-bar/PP, retain all 512 known TRN symbols, then 384 report
    # symbols and 96 terminator symbols. Wire order: report low 16, ext high 8.
    count = 512 + 384 + 96
    lines = ["/* Generated by tools/generate_k56flex_upstream_vectors.py.",
             " * MicaEmu native/k56flex_training_tx.inc SHA256:",
             f" * {digest}",
             " * 3200 baud; report 8990, extension 63; each byte holds four",
             " * point sign pairs (bit 0: real negative; bit 1: imag negative).",
             " * Equalized points only, NOT recorded PCM or hardware evidence. */",
             "#ifndef K56FLEX_UPSTREAM_VECTORS_H", "#define K56FLEX_UPSTREAM_VECTORS_H",
             f"#define K56U_VECTOR_SYMBOLS {count}"]
    for tap in (5, 18):
        tx = lib.mica_k56_training_new(3200, 0, tap, 128, 512, 0x638990)
        if not tx:
            raise RuntimeError("training transmitter init failed")
        try:
            if lib.mica_k56_training_report_length(tx, 384):
                raise RuntimeError("setting report length failed")
            p = (ct.c_float * 2)()
            for _ in range(128 + 16 + 288):
                lib.mica_k56_training_next_point(tx, p)
            packed = bytearray(count // 4)
            for n in range(count):
                lib.mica_k56_training_next_point(tx, p)
                signs = int(p[0] < 0) | (int(p[1] < 0) << 1)
                packed[n // 4] |= signs << (2 * (n % 4))
            lines.append(f"static const uint8_t k56u_vector_{tap}[{len(packed)}] = {{")
            for start in range(0, len(packed), 16):
                lines.append("    " + ", ".join(f"0x{b:02x}" for b in packed[start:start+16]) + ",")
            lines.append("};")
        finally:
            lib.mica_k56_training_free(tx)
    lines.append("#endif")
    target = Path(__file__).resolve().parents[1] / "k56flex_upstream_vectors.h"
    target.write_text("\n".join(lines) + "\n")
    print(target)


if __name__ == "__main__":
    main()
