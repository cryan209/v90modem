static int run(const uint8_t *cw, int n, int offset, bool alaw, int *bar_at)
{
    v92_su_t s;
    int acquired = -1;

    v92_su_init(&s, alaw);
    *bar_at = -1;
    for (int i = 0;  i < offset;  i++)
        v92_su_put(&s, alaw ? 0xd5 : 0xff);
    for (int i = 0;  i < n;  i++) {
        v92_su_event_t e = v92_su_put(&s, cw[i]);
        if (e == V92_SU_ACQUIRED && acquired < 0)
            acquired = i;
        if (e == V92_SU_BAR && *bar_at < 0)
            *bar_at = i;
    }
    return acquired;
}

/* 144T Su, 24.5T Su-bar, then Su half a symbol later (9.5.2.1.7), as a line
 * leaves it: the 1333 1/3 Hz fundamental only, through a short ISI filter. */
static int synth(uint8_t *cw, bool alaw, double phase0, bool reverse)
{
    double a = 3500.0, y[400];
    int n = 0;

    for (int k = 0;  k < 24;  k++)
        y[n++] = 0.0;
    for (int k = 0;  k < 240;  k++, n++) {
        double t = k;                       /* symbols since Su began */
        double ph = phase0 + 2.0*M_PI*t/6.0;
        if (!reverse)
            ;
        else if (t >= 144.0  &&  t < 168.5)
            ph += M_PI;                     /* Su-bar */
        else if (t >= 168.5)
            ph += 2.0*M_PI*0.5/6.0;         /* returned Su, half a symbol later */
        y[n] = a*sin(ph);
    }
    for (int i = n - 1;  i >= 2;  i--)
        y[i] = 0.7*y[i] + 0.2*y[i - 1] + 0.1*y[i - 2];
    for (int i = 0;  i < n;  i++) {
        int16_t v = (int16_t) lrint(y[i]);
        cw[i] = alaw ? linear_to_alaw(v) : linear_to_ulaw(v);
    }
    return n;
}

/* The 8.5.6 sequence itself, {+1,0,+1,-1,0,-1} x level, with nothing taken
 * off it: two thirds of its power is at 4000 Hz.  su_len symbols of Su, 24 of
 * Su-bar, then Su (held as a pure 1333 1/3 Hz sine when held_sine).  f1333
 * scales the 1333 1/3 Hz part of Su and Su-bar, the 4000 Hz part kept.
 * Peers measured by D-Modem's interop notes (d-modem.github.io/D-Modem/
 * interop-details/): Broadcom sends 96T of Su, not 144T; Conexant HSF sends
 * Su with most of its energy at 4000 Hz, 24T of Su-bar, and then holds a sine.
 * The detector needs the 1333 Hz part at about 30% of the spec Su's at this
 * level: at 10% it misses the burst and acquires the held Su instead. */
static int synth_86(uint8_t *cw, bool alaw, int su_len, double f1333, double level, bool held_sine)
{
    static const double base[6] = {1, 0, 1, -1, 0, -1};
    int n = 0;

    for (int k = 0;  k < 24;  k++)
        cw[n++] = alaw ? linear_to_alaw(0) : linear_to_ulaw(0);
    for (int k = 0;  k < su_len + 24 + 150;  k++) {
        int m = k % 6;
        double x4 = (m & 1)  ?  -2.0/3.0  :  2.0/3.0;   /* the 4000 Hz part */
        double x1 = base[m] - x4;                        /* the rest: 1333 Hz */
        double v;

        if (k >= su_len + 24  &&  held_sine)
            v = x1;
        else
            v = f1333*x1 + x4;
        if (k >= su_len  &&  k < su_len + 24)
            v = -v;                                      /* Su-bar */
        cw[n++] = alaw ? linear_to_alaw((int16_t) lrint(level*v))
                       : linear_to_ulaw((int16_t) lrint(level*v));
    }
    return n;
}

/* 9.5.1.1.6-8: Su then Su-bar through a band-limited pulse (raised cosine,
 * rolloff 0.25) delayed by `delay` symbols, gain `gain` (negative: an
 * inverted line).  Returns the Jp extension measured at Su-bar; with it,
 * the delay, and Su-bar's half symbol (9.5.2.1.7), the analogue modem's
 * pulse should land a whole number of symbols late. */
static double jp_extension(double delay, double gain, bool alaw, int offset, bool *ok)
{
    static const double base[6] = {1, 0, 1, -1, 0, -1};
    v92_su_t s;
    double f = -1.0;

    v92_su_init(&s, alaw);
    *ok = false;
    for (int i = 0;  i < offset;  i++)
        v92_su_put(&s, alaw ? 0xd5 : 0xff);
    for (int n = 0;  n < 24 + 144 + 24 + 60;  n++) {
        double y = 0.0;

        for (int m = 0;  m < 144 + 24 + 60;  m++) {
            double t = n - 24 - m - delay, p;
            double x = base[m % 6]*(m >= 144  &&  m < 168  ?  -1.0  :  1.0);

            if (fabs(t) > 14.0)
                continue;
            p = fabs(t) < 1e-9 ? 1.0 : sin(M_PI*t)/(M_PI*t);
            p *= fabs(fabs(0.5*t) - 1.0) < 1e-9 ? M_PI/4.0
                                                : cos(0.25*M_PI*t)/(1.0 - 0.25*t*t);
            y += x*p;
        }
        y *= gain*4000.0;
        if (v92_su_put(&s, alaw ? linear_to_alaw((int16_t) lrint(y))
                                : linear_to_ulaw((int16_t) lrint(y))) == V92_SU_BAR) {
            *ok = v92_su_jp_phase(&s, &f, NULL);
            break;
        }
    }
    return f;
}

static int check_jp_phase(void)
{
    int fails = 0;

    for (int i = 0;  i < 20;  i++) {
        double frac_delay = 3.0 + i/20.0;
        for (int off = 0;  off < 6;  off++) {
            bool ok;
            double gain = (off & 1) ? -1.0 : 1.0;
            double f = jp_extension(frac_delay, gain, off >= 3, off, &ok);
            double r = frac_delay + 0.5 + f;
            double err = fabs(r - floor(r + 0.5));

            /* A-law's coarser steps leave up to 0.025T on 144T of Su;
             * 0.04T costs under 1% of the main tap's energy. */
            if (!ok  ||  err > 0.04) {
                printf("  Jp phase: delay %.2f offset %d gain %+.0f %s: extension %.3f, error %.3f  WRONG\n",
                       frac_delay, off, gain, off >= 3 ? "alaw" : "ulaw", f, err);
                fails++;
            }
        }
    }
    printf("  Jp phase: 120 delays/alignments/polarities/laws, %d wrong\n", fails);
    return fails;
}

/* Su-bar must be reported inside [lo, hi] (codeword index), or never when lo < 0. */
static int check(const char *name, const uint8_t *cw, int n, bool alaw, int lo, int hi)
{
    int fails = 0;

    for (int off = 0;  off < 6;  off++) {
        int bar;
        int acq = run(cw, n, off, alaw, &bar);
        bool ok = acq >= 0  &&  (lo < 0  ?  bar < 0  :  (bar >= lo  &&  bar <= hi));
        printf("  %-22s offset %d: Su at %4d, Su-bar at %4d  %s\n",
               name, off, acq, bar, ok ? "ok" : "MISSED");
        fails += !ok;
    }
    return fails;
}

int main(void)
{
    uint8_t cw[400];
    int fails = 0;

    /* Su-bar on the wire: attempt 1 at codewords ~304-328, attempt 2 ~305-330. */
    fails += check("slmodemd attempt 1", su_attempt1, (int) sizeof(su_attempt1), false, 304, 330);
    fails += check("slmodemd attempt 2", su_attempt2, (int) sizeof(su_attempt2), false, 304, 332);
    for (int p = 0;  p < 12;  p++) {
        char name[32];
        int n;

        snprintf(name, sizeof(name), "synthetic %3d deg ulaw", p*30);
        n = synth(cw, false, p*M_PI/6.0, true);
        fails += check(name, cw, n, false, 168, 193);
        snprintf(name, sizeof(name), "synthetic %3d deg alaw", p*30);
        n = synth(cw, true, p*M_PI/6.0, true);
        fails += check(name, cw, n, true, 168, 193);
        snprintf(name, sizeof(name), "no reversal %3d deg", p*30);
        n = synth(cw, false, p*M_PI/6.0, false);
        fails += check(name, cw, n, false, -1, -1);
    }
    /* Su-bar starts at codeword 24 + su_len and lasts 24. */
    for (int law = 0;  law < 2;  law++) {
        bool alaw = law;
        int n;

        n = synth_86(cw, alaw, 144, 1.0, 6000.0, false);
        fails += check(alaw ? "8.5.6 144T alaw" : "8.5.6 144T ulaw", cw, n, alaw, 168, 192);
        n = synth_86(cw, alaw, 144, 1.0, 1500.0, false);
        fails += check(alaw ? "8.5.6 144T -12dB alaw" : "8.5.6 144T -12dB ulaw", cw, n, alaw, 168, 192);
        n = synth_86(cw, alaw, 96, 1.0, 6000.0, false);
        fails += check(alaw ? "Broadcom 96T alaw" : "Broadcom 96T ulaw", cw, n, alaw, 120, 144);
        n = synth_86(cw, alaw, 144, 0.3, 6000.0, true);
        fails += check(alaw ? "HSF-like 4kHz alaw" : "HSF-like 4kHz ulaw", cw, n, alaw, 168, 192);
    }
    fails += check_jp_phase();
    printf(fails ? "FAIL: %d missed Su-bar\n" : "PASS\n", fails);
    return fails ? 1 : 0;
}
