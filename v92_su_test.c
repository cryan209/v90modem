static int run(const uint8_t *cw, int n, int offset, bool alaw, int *bar_at)
{
    v92_su_t s;
    int acquired = -1;

    v92_su_init(&s, alaw);
    *bar_at = -1;
    for (int i = 0;  i < offset;  i++)
        v92_su_put(&s, alaw ? 0xd5 : 0xff);
    for (int i = 0;  i < n;  i++) {
        v92_su_event_t e = v92_su_put(&s, cw[i]);
        if (e == V92_SU_ACQUIRED && acquired < 0)
            acquired = i;
        if (e == V92_SU_BAR && *bar_at < 0)
            *bar_at = i;
    }
    return acquired;
}

/* 144T Su, 24.5T Su-bar, then Su half a symbol later (9.5.2.1.7), as a line
 * leaves it: the 1333 1/3 Hz fundamental only, through a short ISI filter. */
static int synth(uint8_t *cw, bool alaw, double phase0, bool reverse)
{
    double a = 3500.0, y[400];
    int n = 0;

    for (int k = 0;  k < 24;  k++)
        y[n++] = 0.0;
    for (int k = 0;  k < 240;  k++, n++) {
        double t = k;                       /* symbols since Su began */
        double ph = phase0 + 2.0*M_PI*t/6.0;
        if (!reverse)
            ;
        else if (t >= 144.0  &&  t < 168.5)
            ph += M_PI;                     /* Su-bar */
        else if (t >= 168.5)
            ph += 2.0*M_PI*0.5/6.0;         /* returned Su, half a symbol later */
        y[n] = a*sin(ph);
    }
    for (int i = n - 1;  i >= 2;  i--)
        y[i] = 0.7*y[i] + 0.2*y[i - 1] + 0.1*y[i - 2];
    for (int i = 0;  i < n;  i++) {
        int16_t v = (int16_t) lrint(y[i]);
        cw[i] = alaw ? linear_to_alaw(v) : linear_to_ulaw(v);
    }
    return n;
}

/* Su-bar must be reported inside [lo, hi] (codeword index), or never when lo < 0. */
static int check(const char *name, const uint8_t *cw, int n, bool alaw, int lo, int hi)
{
    int fails = 0;

    for (int off = 0;  off < 6;  off++) {
        int bar;
        int acq = run(cw, n, off, alaw, &bar);
        bool ok = acq >= 0  &&  (lo < 0  ?  bar < 0  :  (bar >= lo  &&  bar <= hi));
        printf("  %-22s offset %d: Su at %4d, Su-bar at %4d  %s\n",
               name, off, acq, bar, ok ? "ok" : "MISSED");
        fails += !ok;
    }
    return fails;
}

int main(void)
{
    uint8_t cw[400];
    int fails = 0;

    /* Su-bar on the wire: attempt 1 at codewords ~304-328, attempt 2 ~305-330. */
    fails += check("slmodemd attempt 1", su_attempt1, (int) sizeof(su_attempt1), false, 304, 330);
    fails += check("slmodemd attempt 2", su_attempt2, (int) sizeof(su_attempt2), false, 304, 332);
    for (int p = 0;  p < 12;  p++) {
        char name[32];
        int n;

        snprintf(name, sizeof(name), "synthetic %3d deg ulaw", p*30);
        n = synth(cw, false, p*M_PI/6.0, true);
        fails += check(name, cw, n, false, 168, 193);
        snprintf(name, sizeof(name), "synthetic %3d deg alaw", p*30);
        n = synth(cw, true, p*M_PI/6.0, true);
        fails += check(name, cw, n, true, 168, 193);
        snprintf(name, sizeof(name), "no reversal %3d deg", p*30);
        n = synth(cw, false, p*M_PI/6.0, false);
        fails += check(name, cw, n, false, -1, -1);
    }
    printf(fails ? "FAIL: %d missed Su-bar\n" : "PASS\n", fails);
    return fails ? 1 : 0;
}
